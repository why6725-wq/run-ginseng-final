/** AI 프롬프트에 넣을 용어 정의 블록 */
export function termsForPrompt(): string {
  const section = (title: string, dict: Record<string, TermEntry>) =>
    `[${title}]\n` +
    Object.entries(dict)
      .map(([k, v]) => `- ${k}(${v.hanja}): ${v.long}`)
      .join('\n')

  return [
    section('십신', TEN_GOD_TERMS),
    section('오행', ELEMENT_TERMS),
    section('구조 용어', STRUCTURE_TERMS),
  ].join('\n\n')
}
